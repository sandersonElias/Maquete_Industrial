const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({channel:'msedge',headless:true});
 try{
  const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  const base=process.env.CCO_TEST_URL||'http://127.0.0.1:18080';
  const initial=await (await page.request.get(base+'/api/state')).json();
  assert.equal(initial.arduino.port,'SIMULADO','Execute somente em uma instância de simulação isolada');
  await page.request.post(base+'/api/mock/reset');
  await page.goto(base+'/configurar.html');
  await page.waitForFunction(()=>document.querySelector('#modeStatus').textContent.includes('bloqueadas'));
  const blocked=await page.request.post(base+'/api/locomotives/L01/command',{data:{action:'FORWARD'}});
  assert.equal(blocked.status(),400);assert.match((await blocked.json()).error,/Configuração/);
  await page.request.post(base+'/api/mock/input',{data:{pin:'D3',active:true}});
  await page.waitForFunction(()=>document.querySelector('#lastInput').textContent.includes('D3'));
  assert.equal(await page.locator('#sensor-S02').evaluate(node=>node.classList.contains('active')),true);
  await page.locator('#sensor-S02').click();assert.match(await page.locator('#mapSelection').innerText(),/S02/);
  await page.request.post(base+'/api/mock/input',{data:{pin:'D3',active:false}});
  await page.locator('#pin-S01').selectOption('D3');
  assert.equal(await page.locator('#testAngleButton').isDisabled(),true);
  await page.locator('#saveHardware').click();
  await page.waitForFunction(()=>document.querySelector('#configMessage').textContent.includes('pino diferente'));
  await page.locator('#pin-S01').selectOption('D8');await page.locator('#pin-S07').selectOption('D2');
  await page.locator('#pin-C1').selectOption('A1');await page.locator('#normal-C1').fill('50');await page.locator('#reverse-C1').fill('95');
  await page.locator('#saveHardware').click();
  await page.waitForFunction(()=>document.querySelector('#dirtyStatus').textContent==='Configuração salva');
  await page.locator('#row-C1 button').first().click();
  await page.waitForFunction(()=>document.querySelector('#servoStatus').textContent.includes('C1 · 50°'));
  await page.locator('#plusAngle').click();
  await page.waitForFunction(()=>document.querySelector('#servoStatus').textContent.includes('C1 · 55°'));
  await page.locator('#configEmergency').click();
  await page.waitForFunction(()=>document.querySelector('#configEmergency').textContent.includes('Rearmar'));
  assert.equal(await page.locator('#testAngleButton').isDisabled(),true);
  await page.locator('#configEmergency').click();
  await page.waitForFunction(()=>document.querySelector('#configEmergency').textContent==='Parada de emergência');
  await page.screenshot({path:process.env.TEMP+'/cco-configuracao-desktop.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:process.env.TEMP+'/cco-configuracao-mobile.png',fullPage:true});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.locator('#backToCCO').click();await page.waitForURL(base+'/');
  const state=await (await page.request.get(base+'/api/state')).json();
  assert.equal(state.hardware_setup.active,false);assert.equal(state.hardware.config.sensors.S01,'D8');assert.equal(state.hardware.config.servos.C1.pin,'A1');
  await page.goto(base+'/configurar.html');await page.locator('#pin-S01').waitFor();
  assert.equal(await page.locator('#pin-S01').inputValue(),'D8');
  await page.locator('#backToCCO').click();await page.waitForURL(base+'/');
  assert.deepEqual(errors,[]);
  console.log('Configuração: bloqueios, sensor ao vivo, mapa, validação, salvamento, servo, emergência e tela móvel OK');
 }finally{await browser.close()}
})().catch(error=>{console.error(error);process.exitCode=1});
